import os
from pathlib import Path

from anthropic import Anthropic
from dotenv import load_dotenv

from llm.prompt import SYSTEM_PROMPT, build_prompt


BASE_DIR = Path(__file__).resolve().parent.parent

load_dotenv(BASE_DIR / ".env")


MODEL_NAME = "claude-haiku-4-5-20251001"

MAX_TOKENS = 500

TEMPERATURE = 0.3


def load_claude():
    """
    Create and return the Anthropic client.
    """

    api_key = os.getenv("ANTHROPIC_API_KEY")

    if not api_key:
        raise ValueError(
            "ANTHROPIC_API_KEY not found.\n"
            "Make sure a .env file exists in the project root "
            "and contains:\n\n"
            "ANTHROPIC_API_KEY=your_api_key"
        )

    return Anthropic(api_key=api_key)


def generate_response(
    question: str,
    context: str,
    history: str = "",
    memory: str = "",
    service_recommendation: dict | None = None,
) -> str:
    """
    Generate a VYRA response using:

    - current user question
    - retrieved knowledge
    - recent conversation history
    - long-term client memory
    - optional service recommendation

    The service recommendation is generated by the
    ServiceRecommendationService. This function only passes
    that structured result to the prompt builder.
    """

    client = load_claude()

    user_prompt = build_prompt(
        question=question,
        context=context,
        history=history,
        memory=memory,
        service_recommendation=service_recommendation,
    )

    response = client.messages.create(
        model=MODEL_NAME,
        system=SYSTEM_PROMPT,
        max_tokens=MAX_TOKENS,
        temperature=TEMPERATURE,
        messages=[
            {
                "role": "user",
                "content": user_prompt,
            }
        ],
    )

    if not response.content:
        raise RuntimeError(
            "Claude returned an empty response."
        )

    return response.content[0].text